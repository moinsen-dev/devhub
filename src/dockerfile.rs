/// Format a command string for Docker CMD instruction
fn format_command_for_docker(command: &str) -> String {
    // Split command into parts and format as JSON array
    let parts: Vec<&str> = command.split_whitespace().collect();
    let json_parts: Vec<String> = parts.iter().map(|p| format!("\"{}\"", p)).collect();
    format!("[{}]", json_parts.join(", "))
}

/// Check if a project has a Dockerfile for a service
pub fn has_dockerfile(project_path: &Path, service: &Service) -> bool {
    // Check for service-specific Dockerfile
    if let Some(ref dockerfile) = service.dockerfile {
        return project_path.join(dockerfile).exists();
    }

    // Check for standard Dockerfile locations
    let dockerfile_paths = [
        project_path.join("Dockerfile"),
        project_path
            .join(".devhub")
            .join(format!("Dockerfile.{}", service.name)),
    ];

    // If service has a cwd, also check there
    if let Some(ref cwd) = service.cwd {
        let service_dir = project_path.join(cwd);
        if service_dir.join("Dockerfile").exists() {
            return true;
        }
    }

    dockerfile_paths.iter().any(|p| p.exists())
}

/// Write a generated Dockerfile for a service
pub fn write_dockerfile(project_path: &Path, service: &Service, manifest: &Manifest) -> Result<()> {
    let devhub_dir = project_path.join(".devhub");
    std::fs::create_dir_all(&devhub_dir)?;

    let dockerfile_path = devhub_dir.join(format!("Dockerfile.{}", service.name));
    let content = generate_dockerfile(service, manifest);

    if content.is_empty() {
        return Ok(()); // Docker Compose services don't need a Dockerfile
    }

    std::fs::write(&dockerfile_path, content)?;
    tracing::info!(
        "Generated Dockerfile for service '{}' at {:?}",
        service.name,
        dockerfile_path
    );

    Ok(())
}

/// Generate Dockerfiles for all services in a project
pub fn generate_project_dockerfiles(project_path: &Path, manifest: &Manifest) -> Result<()> {
    for service in &manifest.services {
        // Skip if service already has a Dockerfile
        if has_dockerfile(project_path, service) {
            tracing::debug!(
                "Service '{}' already has a Dockerfile, skipping generation",
                service.name
            );
            continue;
        }

        // Skip Docker Compose services
        if service.service_type == ServiceType::DockerCompose {
            continue;
        }

        write_dockerfile(project_path, service, manifest)?;
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;

    fn create_test_service(name: &str, service_type: ServiceType, command: &str) -> Service {
        Service {
            name: name.to_string(),
            service_type,
            command: command.to_string(),
            port: 8080,
            cwd: None,
            health_check: None,
            subdomain: None,
            main: false,
            depends_on: vec![],
            env: HashMap::new(),
            env_file: None,
            mode: None,
            image: None,
            dockerfile: None,
            build_context: None,
            internal_port: None,
            networks: vec![],
            volumes: vec![],
        }
    }

    fn create_test_manifest() -> Manifest {
        Manifest::template("test-project")
    }

    #[test]
    fn test_get_base_image() {
        assert_eq!(get_base_image(&ServiceType::Node), "node:22-alpine");
        assert_eq!(get_base_image(&ServiceType::Python), "python:3.12-slim");
        assert_eq!(get_base_image(&ServiceType::Dart), "dart:3.5");
        assert_eq!(get_base_image(&ServiceType::Go), "golang:1.22-alpine");
        assert_eq!(get_base_image(&ServiceType::RustBinary), "rust:1.75-alpine");
    }

    #[test]
    fn test_format_command_for_docker() {
        assert_eq!(
            format_command_for_docker("npm start"),
            "[\"npm\", \"start\"]"
        );
        assert_eq!(
            format_command_for_docker("dart run bin/server.dart"),
            "[\"dart\", \"run\", \"bin/server.dart\"]"
        );
    }

    #[test]
    fn test_generate_node_dockerfile() {
        let service = create_test_service("api", ServiceType::Node, "npm start");
        let manifest = create_test_manifest();
        let dockerfile = generate_dockerfile(&service, &manifest);

        assert!(dockerfile.contains("FROM node:22-alpine"));
        assert!(dockerfile.contains("EXPOSE 8080"));
        assert!(dockerfile.contains("npm ci"));
    }

    #[test]
    fn test_generate_dart_dockerfile() {
        let service = create_test_service("api", ServiceType::Dart, "dart run bin/server.dart");
        let manifest = create_test_manifest();
        let dockerfile = generate_dockerfile(&service, &manifest);

        assert!(dockerfile.contains("FROM dart:3.5"));
        assert!(dockerfile.contains("dart pub get"));
        assert!(dockerfile.contains("EXPOSE 8080"));
    }

    #[test]
    fn test_generate_python_dockerfile() {
        let service = create_test_service("api", ServiceType::Python, "python -m uvicorn main:app");
        let manifest = create_test_manifest();
        let dockerfile = generate_dockerfile(&service, &manifest);

        assert!(dockerfile.contains("FROM python:3.12-slim"));
        assert!(dockerfile.contains("pip install"));
        assert!(dockerfile.contains("EXPOSE 8080"));
    }

    #[test]
    fn test_custom_base_image() {
        let mut service = create_test_service("api", ServiceType::Node, "npm start");
        service.image = Some("node:20-bullseye".to_string());
        let manifest = create_test_manifest();
        let dockerfile = generate_dockerfile(&service, &manifest);

        assert!(dockerfile.contains("FROM node:20-bullseye"));
        assert!(!dockerfile.contains("node:22-alpine"));
    }
}
