/// Generate a Dockerfile for Go services
fn generate_go_dockerfile(service: &Service, base_image: &str) -> String {
    let port = service.internal_port.unwrap_or(service.port);
    let workdir = service.cwd.as_deref().unwrap_or(".");

    format!(
        r#"# Auto-generated by DevHub for container mode
# Service: {name}
FROM {base_image} AS builder

WORKDIR /app/{workdir}

# Download dependencies
COPY go.mod go.sum* ./
RUN go mod download 2>/dev/null || true

# Copy source and build
COPY . .
RUN CGO_ENABLED=0 go build -o /app/service .

# Runtime stage
FROM alpine:latest
RUN apk --no-cache add ca-certificates
WORKDIR /app
COPY --from=builder /app/service .

# Expose the internal port
EXPOSE {port}

# Start the service
CMD ["./service"]
"#,
        name = service.name,
        base_image = base_image,
        workdir = workdir,
        port = port,
    )
}

/// Generate a Dockerfile for Dart services (including Serverpod)
fn generate_dart_dockerfile(service: &Service, manifest: &Manifest, base_image: &str) -> String {
    let port = service.internal_port.unwrap_or(service.port);
    let workdir = service.cwd.as_deref().unwrap_or(".");

    // Check if this looks like a Serverpod project
    let is_serverpod = service.command.contains("serverpod")
        || manifest.project.name.contains("serverpod")
        || service.name.contains("server");

    if is_serverpod {
        generate_serverpod_dockerfile(service, base_image, port, workdir)
    } else {
        format!(
            r#"# Auto-generated by DevHub for container mode
# Service: {name}
FROM {base_image}

WORKDIR /app/{workdir}

# Get dependencies
COPY pubspec.* ./
RUN dart pub get

# Copy source code
COPY . .

# Expose the internal port
EXPOSE {port}

# Start the service
CMD {command}
"#,
            name = service.name,
            base_image = base_image,
            workdir = workdir,
            port = port,
            command = format_command_for_docker(&service.command),
        )
    }
}

/// Generate a Dockerfile for Serverpod projects
fn generate_serverpod_dockerfile(
    service: &Service,
    base_image: &str,
    port: u16,
    workdir: &str,
) -> String {
    format!(
        r#"# Auto-generated by DevHub for container mode
# Service: {name} (Serverpod)
FROM {base_image}

WORKDIR /app/{workdir}

# Install serverpod_cli
RUN dart pub global activate serverpod_cli

# Get dependencies
COPY pubspec.* ./
RUN dart pub get

# Copy source code
COPY . .

# Generate code (if needed)
RUN dart pub get && \
    (serverpod generate 2>/dev/null || true)

# Build for production
RUN dart compile exe bin/main.dart -o bin/server

# Expose the internal port
EXPOSE {port}

# Start the service
CMD ["./bin/server", "--mode", "production"]
"#,
        name = service.name,
        base_image = base_image,
        workdir = workdir,
        port = port,
    )
}

/// Generate a Dockerfile for Rust services
fn generate_rust_dockerfile(service: &Service, base_image: &str) -> String {
    let port = service.internal_port.unwrap_or(service.port);
    let workdir = service.cwd.as_deref().unwrap_or(".");

    format!(
        r#"# Auto-generated by DevHub for container mode
# Service: {name}
FROM {base_image} AS builder

WORKDIR /app/{workdir}

# Create a dummy project to cache dependencies
RUN mkdir src && echo "fn main() {{}}" > src/main.rs
COPY Cargo.toml Cargo.lock* ./
RUN cargo build --release 2>/dev/null || true
RUN rm -rf src

# Copy real source and build
COPY . .
RUN cargo build --release

# Runtime stage
FROM alpine:latest
RUN apk --no-cache add ca-certificates libgcc
WORKDIR /app
COPY --from=builder /app/target/release/* ./

# Expose the internal port
EXPOSE {port}

# Start the service
CMD {command}
"#,
        name = service.name,
        base_image = base_image,
        workdir = workdir,
        port = port,
        command = format_command_for_docker(&service.command),
    )
}

