//! Dockerfile generation for DevHub container mode.
//!
//! This module provides auto-generation of Dockerfiles for projects
//! that want to run in container mode but don't have their own Dockerfile.
//!
//! Note: This module is foundation code for CR-001 (Docker Network Isolation).
//! Functions are not yet wired into the main CLI but will be in a future release.

#![allow(dead_code)]

use anyhow::Result;
use std::path::Path;

use crate::manifest::{Manifest, Service, ServiceType};

/// Get the default base image for a service type
pub fn get_base_image(service_type: &ServiceType) -> &'static str {
    match service_type {
        ServiceType::Node => "node:22-alpine",
        ServiceType::Python => "python:3.12-slim",
        ServiceType::Go => "golang:1.22-alpine",
        ServiceType::Dart => "dart:3.5",
        ServiceType::RustBinary => "rust:1.75-alpine",
        ServiceType::DockerCompose => "alpine:latest",
        ServiceType::Shell => "alpine:latest",
    }
}

/// Generate a Dockerfile for a service
pub fn generate_dockerfile(service: &Service, manifest: &Manifest) -> String {
    // Use custom image if specified, otherwise use default for service type
    let base_image = service
        .image
        .as_deref()
        .unwrap_or_else(|| get_base_image(&service.service_type));

    match service.service_type {
        ServiceType::Node => generate_node_dockerfile(service, base_image),
        ServiceType::Python => generate_python_dockerfile(service, base_image),
        ServiceType::Go => generate_go_dockerfile(service, base_image),
        ServiceType::Dart => generate_dart_dockerfile(service, manifest, base_image),
        ServiceType::RustBinary => generate_rust_dockerfile(service, base_image),
        ServiceType::Shell => generate_shell_dockerfile(service, base_image),
        ServiceType::DockerCompose => {
            // Docker Compose services shouldn't need a Dockerfile from us
            String::new()
        }
    }
}

/// Generate a Dockerfile for Node.js services
fn generate_node_dockerfile(service: &Service, base_image: &str) -> String {
    let port = service.internal_port.unwrap_or(service.port);
    let workdir = service.cwd.as_deref().unwrap_or(".");

    format!(
        r#"# Auto-generated by DevHub for container mode
# Service: {name}
FROM {base_image}

WORKDIR /app/{workdir}

# Install dependencies
COPY package*.json ./
RUN npm ci --only=production 2>/dev/null || npm install --production

# Copy source code
COPY . .

# Expose the internal port
EXPOSE {port}

# Start the service
CMD {command}
"#,
        name = service.name,
        base_image = base_image,
        workdir = workdir,
        port = port,
        command = format_command_for_docker(&service.command),
    )
}

